/// `MuJoCo` 闭环模式的空地图（无静态先验，由深度感知填充）。
/// 范围覆盖 `firefly-mujoco` 场景：x∈[0,36]、y∈[-5,21]、z∈[0,5.2]。
#[must_use]
pub fn empty_map_file() -> MapFile {
    MapFile {
        resolution: 0.4,
        origin: [0.0, -5.0, 0.0],
        dims: [90, 65, 13],
        occupied: Vec::new(),
        decor: Vec::new(),
        motions: Vec::new(),
    }
}

