//! Occupancy map capabilities and CLIP chair embedding from `mapTypedefs.hpp`.
use nalgebra::Vector3;

/// The selected backend corresponds to multiresolution occupancy or occupancy
/// with color and instance IDs, according to the caller's concrete map type.
/// Field queries return None exactly when safe interpolation has no valid value.
pub trait SupereightMapType {
    fn interp_field_safe(&self, point: &Vector3<f32>) -> Option<f32>;
}

/// Shared mutable occupancy storage retained by the estimator and integrator.
#[derive(Clone, Debug)]
pub struct OccupancyMap {
    pub inner: std::sync::Arc<std::sync::RwLock<firefly_supereight2::map::Map>>,
}
pub type SharedOccupancyMaps =
    std::sync::Arc<std::sync::RwLock<std::collections::BTreeMap<u64, OccupancyMap>>>;
impl OccupancyMap {
    #[must_use]
    pub fn new(map: firefly_supereight2::map::Map) -> Self {
        Self {
            inner: std::sync::Arc::new(std::sync::RwLock::new(map)),
        }
    }
    /// # Errors
    /// Returns an error for invalid configuration or sensor/map data, absent frames/maps,
    /// or a failed storage, integration, alignment, callback, worker or file operation.
    pub fn read(
        &self,
    ) -> firefly_error::Result<std::sync::RwLockReadGuard<'_, firefly_supereight2::map::Map>> {
        self.inner
            .read()
            .map_err(|_| map_access_error("occupancy map read lock poisoned"))
    }
    /// # Errors
    /// Returns an error for invalid configuration or sensor/map data, absent frames/maps,
    /// or a failed storage, integration, alignment, callback, worker or file operation.
    pub fn write(
        &self,
    ) -> firefly_error::Result<std::sync::RwLockWriteGuard<'_, firefly_supereight2::map::Map>> {
        self.inner
            .write()
            .map_err(|_| map_access_error("occupancy map write lock poisoned"))
    }
    #[must_use]
    pub fn identity(&self) -> usize {
        std::sync::Arc::as_ptr(&self.inner) as usize
    }
    /// # Errors
    /// Returns an error for invalid configuration or sensor/map data, absent frames/maps,
    /// or a failed storage, integration, alignment, callback, worker or file operation.
    pub fn snapshot(&self) -> firefly_error::Result<Self> {
        Ok(Self::new(self.read()?.clone()))
    }
}
pub fn map_access_error(message: impl Into<String>) -> firefly_error::Error {
    firefly_error::Error::new(firefly_error::ErrorKind::InvalidArgument, message)
        .with_operation("okvis2_x::occupancy_map")
}
impl SupereightMapType for OccupancyMap {
    fn interp_field_safe(&self, point: &Vector3<f32>) -> Option<f32> {
        let result = self.read().and_then(|map| map.interp_field(point, 0, true));
        match result {
            Ok(value) => value.map(|(value, _)| value),
            Err(error) => {
                log::error!("occupancy interpolation failed: {error}");
                None
            }
        }
    }
}

