//! Fixed-input intermediates for the first room1 stereo-track discrepancy.
//! This diagnostic exports arithmetic variants; completion is not an acceptance
//! claim. The unchanged dataset gate and fixed C++ arithmetic regression provide
//! the numerical checks, with the reference compiler profile stated explicitly.
use firefly_basalt::optical_flow::{
    AffineCompact2,
    frame_to_frame_optical_flow::FrameToFrameOpticalFlow,
    patch::OpticalFlowPatch,
    patterns::{Pattern, Pattern51},
};
use firefly_basalt::utils::ldlt::Ldlt;
use firefly_basalt_headers::image::image::Image;
use firefly_basalt_headers::{calibration::Calibration, camera::generic_camera::GenericCamera};
use nalgebra::{DMatrix, Matrix2, SMatrix, SVector, Vector2};
use serde_json::{Value, json};
use std::{fs::File, io::BufReader};

fn numbers(value: &Value) -> Vec<f32> {
    value
        .as_array()
        .unwrap()
        .iter()
        .map(|v| v.as_f64().unwrap() as f32)
        .collect()
}

// Eigen's complete scalar redux tree, with the contractions emitted by the
// pinned GCC native build. Kept in diagnostics until other platform oracles
// establish whether adopting this arithmetic preserves existing gates.
fn contracted_dot(left: &[f32], right: &[f32]) -> f32 {
    match left.len() {
        1 => left[0] * right[0],
        2 => left[1].mul_add(right[1], left[0] * right[0]),
        3 => left[0].mul_add(right[0], contracted_dot(&left[1..], &right[1..])),
        length => {
            let half = length / 2;
            contracted_dot(&left[..half], &right[..half])
                + contracted_dot(&left[half..], &right[half..])
        }
    }
}

fn balanced_dot(left: &[f32], right: &[f32]) -> f32 {
    if left.len() == 1 {
        left[0] * right[0]
    } else {
        let half = left.len() / 2;
        balanced_dot(&left[..half], &right[..half]) + balanced_dot(&left[half..], &right[half..])
    }
}

fn tracker() -> FrameToFrameOpticalFlow<Pattern51, 52> {
    let mut calibration = Calibration::<f64>::default();
    calibration.intrinsics.push(GenericCamera::default());
    calibration.t_i_c.push(nalgebra::Isometry3::identity());
    FrameToFrameOpticalFlow::<Pattern51, 52>::new(
        firefly_basalt::utils::vio_config::VioConfig {
            optical_flow_max_iterations: 1,
            ..Default::default()
        },
        &calibration,
    )
    .unwrap()
}

fn row_major(matrix: &DMatrix<f32>) -> Vec<f32> {
    (0..matrix.nrows())
        .flat_map(|row| (0..matrix.ncols()).map(move |col| matrix[(row, col)]))
        .collect()
}

#[test]
#[ignore = "requires BASALT_PATCH_TRACE generated by the official C++ probe"]
fn fixed_input_patch_intermediates() {
    type Patch = OpticalFlowPatch<f32, Pattern51, 52>;
    let reference: Vec<Value> = serde_json::from_reader(BufReader::new(
        File::open(std::env::var_os("BASALT_PATCH_TRACE").unwrap()).unwrap(),
    ))
    .unwrap();
    let tracker = tracker();
    let mut result = Vec::new();
    for item in reference {
        let width = item["width"].as_u64().unwrap() as usize;
        let height = item["height"].as_u64().unwrap() as usize;
        let pixels: Vec<u16> = serde_json::from_value(item["pixels"].clone()).unwrap();
        let target_pixels: Vec<u16> =
            serde_json::from_value(item["target_pixels"].clone()).unwrap();
        let image = Image::new(&pixels, width, height, width);
        let target = Image::new(&target_pixels, width, height, width);
        let position = Vector2::from_row_slice(&numbers(&item["pos"]));
        let patch = Patch::new(&image, &position);
        let mut mean = 0.0;
        let mut data = SVector::<f32, 52>::zeros();
        let mut jac = SMatrix::<f32, 52, 3>::zeros();
        Patch::set_data_jac_se2(&image, &position, &mut mean, &mut data, &mut jac);
        let fused_h = DMatrix::from_fn(3, 3, |row, col| {
            (0..52).fold(0.0_f32, |sum, index| {
                jac[(index, row)].mul_add(jac[(index, col)], sum)
            })
        });
        let fused_inverse = Ldlt::new(fused_h.clone()).solve(&DMatrix::identity(3, 3));
        let fused_h = row_major(&fused_h);
        let fused_inverse = row_major(&fused_inverse);
        let hessian = jac.transpose() * jac;
        let hessian: Vec<_> = (0..3)
            .flat_map(|row| (0..3).map(move |col| hessian[(row, col)]))
            .collect();
        let jac: Vec<_> = (0..52)
            .flat_map(|row| (0..3).map(move |col| jac[(row, col)]))
            .collect();
        let hinvjt: Vec<_> = (0..3)
            .flat_map(|row| (0..52).map(move |col| patch.h_se2_inv_j_se2_t[(row, col)]))
            .collect();
        let mut iterations = Vec::new();
        for iteration in item["iterations"].as_array().unwrap() {
            let transform = numbers(&iteration["transform"]);
            let linear = Matrix2::new(transform[0], transform[1], transform[3], transform[4]);
            let translation = Vector2::new(transform[2], transform[5]);
            let mut actual = AffineCompact2 {
                linear,
                translation,
            };
            assert!(tracker.track_point_at_level(&target, &patch, &mut actual));
            let after = [
                actual.linear[(0, 0)],
                actual.linear[(0, 1)],
                actual.translation.x,
                actual.linear[(1, 0)],
                actual.linear[(1, 1)],
                actual.translation.y,
            ];
            let mut pattern = linear * <Pattern51 as Pattern<f32, 52>>::pattern2();
            for mut point in pattern.column_iter_mut() {
                point += translation;
            }
            let mut residual = SVector::<f32, 52>::zeros();
            assert!(patch.residual(&target, &pattern, &mut residual));
            let increment = -patch.h_se2_inv_j_se2_t * residual;
            let exact_residual =
                SVector::<f32, 52>::from_row_slice(&numbers(&iteration["residual"]));
            let exact_h = SMatrix::<f32, 3, 52>::from_row_slice(&numbers(&item["hinvjt"]));
            let isolated_increment = -exact_h * exact_residual;
            let contracted_increment: Vec<_> = (0..3)
                .map(|row| {
                    let left: Vec<_> = (0..52).map(|col| -exact_h[(row, col)]).collect();
                    contracted_dot(&left, exact_residual.as_slice())
                })
                .collect();
            let balanced_increment: Vec<_> = (0..3)
                .map(|row| {
                    let left: Vec<_> = (0..52).map(|col| -exact_h[(row, col)]).collect();
                    balanced_dot(&left, exact_residual.as_slice())
                })
                .collect();
            let pattern: Vec<_> = (0..2)
                .flat_map(|row| (0..52).map(move |col| pattern[(row, col)]))
                .collect();
            iterations.push(json!({"after":after,"pattern":pattern,"residual":residual.as_slice(),"increment":increment.as_slice(),"isolated_increment":isolated_increment.as_slice(),"contracted_increment":contracted_increment,"balanced_increment":balanced_increment}));
        }
        result.push(json!({"reference_input":std::env::var("BASALT_PATCH_TRACE").unwrap(),"reference_profile":item["arithmetic_profile"],"level":item["level"],"mean":mean,"data":data.as_slice(),"jac":jac,"h":hessian,"fused_h":fused_h,"fused_inverse":fused_inverse,"hinvjt":hinvjt,"iterations":iterations}));
    }
    let output = concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../../logs/basalt_optical_flow_patch_rust.json"
    );
    serde_json::to_writer_pretty(File::create(output).unwrap(), &result).unwrap();
}
