use nalgebra::{Matrix3, Vector4};
#[must_use]
pub fn quaternion2rot(q: &Vector4<f64>) -> Matrix3<f64> {
    let mut r = Matrix3::<f64>::zeros();

    r[(0, 0)] = q[0].powf(2.0) + q[1].powf(2.0) - q[2].powf(2.0) - q[3].powf(2.0);
    r[(0, 1)] = 2.0 * (q[1] * q[2] - q[0] * q[3]);
    r[(0, 2)] = 2.0 * (q[1] * q[3] + q[0] * q[2]);
    r[(1, 0)] = 2.0 * (q[1] * q[2] + q[0] * q[3]);
    r[(1, 1)] = q[0].powf(2.0) - q[1].powf(2.0) + q[2].powf(2.0) - q[3].powf(2.0);
    r[(1, 2)] = 2.0 * (q[2] * q[3] - q[0] * q[1]);
    r[(2, 0)] = 2.0 * (q[1] * q[3] - q[0] * q[2]);
    r[(2, 1)] = 2.0 * (q[2] * q[3] + q[0] * q[1]);
    r[(2, 2)] = q[0].powf(2.0) - q[1].powf(2.0) - q[2].powf(2.0) + q[3].powf(2.0);

    r
}

#[must_use]
pub fn rot2quaternion(r: &Matrix3<f64>) -> Vector4<f64> {
    let mut q = Vector4::<f64>::zeros();

    q[0] = (r[(0, 0)] + r[(1, 1)] + r[(2, 2)] + 1.0) / 4.0;
    q[1] = (r[(0, 0)] - r[(1, 1)] - r[(2, 2)] + 1.0) / 4.0;
    q[2] = (-r[(0, 0)] + r[(1, 1)] - r[(2, 2)] + 1.0) / 4.0;
    q[3] = (-r[(0, 0)] - r[(1, 1)] + r[(2, 2)] + 1.0) / 4.0;
    if q[0] < 0.0 {
        q[0] = 0.0;
    }
    if q[1] < 0.0 {
        q[1] = 0.0;
    }
    if q[2] < 0.0 {
        q[2] = 0.0;
    }
    if q[3] < 0.0 {
        q[3] = 0.0;
    }
    q[0] = q[0].sqrt();
    q[1] = q[1].sqrt();
    q[2] = q[2].sqrt();
    q[3] = q[3].sqrt();
    if q[0] >= q[1] && q[0] >= q[2] && q[0] >= q[3] {
        q[0] *= 1.0;
        q[1] *= (r[(2, 1)] - r[(1, 2)]) / (r[(2, 1)] - r[(1, 2)]).abs();
        q[2] *= (r[(0, 2)] - r[(2, 0)]) / (r[(0, 2)] - r[(2, 0)]).abs();
        q[3] *= (r[(1, 0)] - r[(0, 1)]) / (r[(1, 0)] - r[(0, 1)]).abs();
    } else if q[1] >= q[0] && q[1] >= q[2] && q[1] >= q[3] {
        q[0] *= (r[(2, 1)] - r[(1, 2)]) / (r[(2, 1)] - r[(1, 2)]).abs();
        q[1] *= 1.0;
        q[2] *= (r[(1, 0)] + r[(0, 1)]) / (r[(1, 0)] + r[(0, 1)]).abs();
        q[3] *= (r[(0, 2)] + r[(2, 0)]) / (r[(0, 2)] + r[(2, 0)]).abs();
    } else if q[2] >= q[0] && q[2] >= q[1] && q[2] >= q[3] {
        q[0] *= (r[(0, 2)] - r[(2, 0)]) / (r[(0, 2)] - r[(2, 0)]).abs();
        q[1] *= (r[(1, 0)] + r[(0, 1)]) / (r[(1, 0)] + r[(0, 1)]).abs();
        q[2] *= 1.0;
        q[3] *= (r[(2, 1)] + r[(1, 2)]) / (r[(2, 1)] + r[(1, 2)]).abs();
    } else if q[3] >= q[0] && q[3] >= q[1] && q[3] >= q[2] {
        q[0] *= (r[(1, 0)] - r[(0, 1)]) / (r[(1, 0)] - r[(0, 1)]).abs();
        q[1] *= (r[(2, 0)] + r[(0, 2)]) / (r[(2, 0)] + r[(0, 2)]).abs();
        q[2] *= (r[(2, 1)] + r[(1, 2)]) / (r[(2, 1)] + r[(1, 2)]).abs();
        q[3] *= 1.0;
    }

    let scale = (q[0] * q[0] + q[1] * q[1] + q[2] * q[2] + q[3] * q[3]).sqrt();
    q[0] /= scale;
    q[1] /= scale;
    q[2] /= scale;
    q[3] /= scale;

    q
}
