        - c123_1[0][(2, 0)] * c123_2[1][(2, 2)];
    row[(0, 6)] = c123_1[2][(0, 0)] * c123_2[2][(0, 2)]
        - c123_1[2][(0, 0)] * c123_2[2][(2, 0)]
