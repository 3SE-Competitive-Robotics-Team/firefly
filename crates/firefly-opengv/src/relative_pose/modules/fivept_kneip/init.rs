use nalgebra::{Matrix3, SMatrix};
#[must_use]
pub fn init_epncp_row_r(
    c123_1: &[Matrix3<f64>; 3],
    c123_2: &[Matrix3<f64>; 3],
) -> SMatrix<f64, 1, 197> {
    let mut row = SMatrix::<f64, 1, 197>::zeros();
    init_epncp_row_r_stage_0(&mut row, c123_1, c123_2);
    init_epncp_row_r_stage_1(&mut row, c123_1, c123_2);
    init_epncp_row_r_stage_2(&mut row, c123_1, c123_2);
    init_epncp_row_r_stage_3(&mut row, c123_1, c123_2);
    init_epncp_row_r_stage_4(&mut row, c123_1, c123_2);
    init_epncp_row_r_stage_5(&mut row, c123_1, c123_2);
    init_epncp_row_r_stage_6(&mut row, c123_1, c123_2);
    init_epncp_row_r_stage_7(&mut row, c123_1, c123_2);
    init_epncp_row_r_stage_8(&mut row, c123_1, c123_2);
    init_epncp_row_r_stage_9(&mut row, c123_1, c123_2);
    init_epncp_row_r_stage_10(&mut row, c123_1, c123_2);
    init_epncp_row_r_stage_11(&mut row, c123_1, c123_2);
    init_epncp_row_r_stage_12(&mut row, c123_1, c123_2);
    init_epncp_row_r_stage_13(&mut row, c123_1, c123_2);
    init_epncp_row_r_stage_14(&mut row, c123_1, c123_2);
    init_epncp_row_r_stage_15(&mut row, c123_1, c123_2);
    row
}
