use nalgebra::SMatrix;
pub fn setup_action_sym_gj(
    m: &SMatrix<f64, 10, 10>,
    c: &SMatrix<f64, 1, 10>,
    _: f64,
    action: &mut SMatrix<f64, 8, 8>,
) -> Option<()> {
    let mut m1 = SMatrix::<f64, 8, 24>::zeros();

    fill_m1_0_0(m, c, &mut m1);
    fill_m1_0_1(m, c, &mut m1);
    fill_m1_0_2(m, c, &mut m1);

    let inv = m1.fixed_view::<7, 7>(0, 0).into_owned().try_inverse()?;

    let p2 = inv * m1.fixed_view::<7, 24>(0, 0);

    m1.fixed_view_mut::<7, 24>(0, 0).copy_from(&p2);

    for i in (0..=6).rev() {
        let factor = m1[(i, 10)] / m1[(7, 10)];
        for j in 0..24 {
            m1[(i, j)] -= factor * m1[(7, j)];
        }
    }
    let mut m2 = vec![vec![0.0; 149]; 141];

    fill_m2_1_0(&m1, &mut m2);
    fill_m2_1_1(&m1, &mut m2);
    fill_m2_1_2(&m1, &mut m2);
    fill_m2_1_3(&m1, &mut m2);
    fill_m2_1_4(&m1, &mut m2);
    fill_m2_1_5(&m1, &mut m2);
    fill_m2_1_6(&m1, &mut m2);
    fill_m2_1_7(&m1, &mut m2);
    fill_m2_1_8(&m1, &mut m2);
    fill_m2_1_9(&m1, &mut m2);
    fill_m2_1_10(&m1, &mut m2);
    fill_m2_1_11(&m1, &mut m2);
    fill_m2_1_12(&m1, &mut m2);
    fill_m2_1_13(&m1, &mut m2);
    fill_m2_1_14(&m1, &mut m2);
    fill_m2_1_15(&m1, &mut m2);
    fill_m2_1_16(&m1, &mut m2);
    fill_m2_1_17(&m1, &mut m2);
    fill_m2_1_18(&m1, &mut m2);
    fill_m2_1_19(&m1, &mut m2);
    fill_m2_1_20(&m1, &mut m2);
    fill_m2_1_21(&m1, &mut m2);
    fill_m2_1_22(&m1, &mut m2);
    fill_m2_1_23(&m1, &mut m2);
    fill_m2_1_24(&m1, &mut m2);
    fill_m2_1_25(&m1, &mut m2);
    fill_m2_1_26(&m1, &mut m2);
    fill_m2_1_27(&m1, &mut m2);
    fill_m2_1_28(&m1, &mut m2);
    fill_m2_1_29(&m1, &mut m2);
    fill_m2_1_30(&m1, &mut m2);
    fill_m2_1_31(&m1, &mut m2);
    fill_m2_1_32(&m1, &mut m2);
    fill_m2_1_33(&m1, &mut m2);
    fill_m2_1_34(&m1, &mut m2);
    fill_m2_1_35(&m1, &mut m2);
    fill_m2_1_36(&m1, &mut m2);
    fill_m2_1_37(&m1, &mut m2);
    fill_m2_1_38(&m1, &mut m2);
    fill_m2_1_39(&m1, &mut m2);
    fill_m2_1_40(&m1, &mut m2);
    fill_m2_1_41(&m1, &mut m2);
    fill_m2_1_42(&m1, &mut m2);
    fill_m2_1_43(&m1, &mut m2);

    if !crate::math::gauss_jordan::gauss_jordan(&mut m2, 121) {
        return None;
    }

    *action = SMatrix::zeros();

    for s in 0..8 {
        action[(0, s)] -= m2[121][141 + s];
    }
    for s in 0..8 {
        action[(1, s)] -= m2[122][141 + s];
    }
    for s in 0..8 {
        action[(2, s)] -= m2[123][141 + s];
    }
    for s in 0..8 {
        action[(3, s)] -= m2[124][141 + s];
    }
    action[(4, 0)] = 1.0;

    action[(5, 1)] = 1.0;

    action[(6, 2)] = 1.0;

    action[(7, 3)] = 1.0;

    Some(())
}

