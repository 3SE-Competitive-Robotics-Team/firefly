use nalgebra::{SMatrix, Vector3};

pub fn init(
    groebner_matrix: &mut SMatrix<f64, 5, 3>,
    a: &SMatrix<f64, 12, 1>,
    n: &SMatrix<f64, 12, 1>,
    c0: &Vector3<f64>,
    c1: &Vector3<f64>,
    c2: &Vector3<f64>,
    c3: &Vector3<f64>,
) {
    let mut temp = c0 - c1;
    let c01w = temp.norm() * temp.norm();
    temp = c0 - c2;
    let c02w = temp.norm() * temp.norm();
    temp = c0 - c3;
    let c03w = temp.norm() * temp.norm();

    groebner_matrix[(0, 0)] =
        -2.0 * n[(0, 0)] * n[(3, 0)] - 2.0 * n[(1, 0)] * n[(4, 0)] - 2.0 * n[(2, 0)] * n[(5, 0)]
            + n[(0, 0)].powf(2.0)
            + n[(3, 0)].powf(2.0)
            + n[(1, 0)].powf(2.0)
            + n[(4, 0)].powf(2.0)
            + n[(2, 0)].powf(2.0)
            + n[(5, 0)].powf(2.0);
    groebner_matrix[(0, 1)] =
        2.0 * a[(0, 0)] * n[(0, 0)] - 2.0 * a[(0, 0)] * n[(3, 0)] - 2.0 * n[(0, 0)] * a[(3, 0)]
            + 2.0 * a[(3, 0)] * n[(3, 0)]
            + 2.0 * a[(1, 0)] * n[(1, 0)]
            - 2.0 * a[(1, 0)] * n[(4, 0)]
            - 2.0 * n[(1, 0)] * a[(4, 0)]
            + 2.0 * a[(4, 0)] * n[(4, 0)]
            + 2.0 * a[(2, 0)] * n[(2, 0)]
            - 2.0 * a[(2, 0)] * n[(5, 0)]
            - 2.0 * n[(2, 0)] * a[(5, 0)]
            + 2.0 * a[(5, 0)] * n[(5, 0)];
    groebner_matrix[(0, 2)] = -c01w + a[(0, 0)].powf(2.0) - 2.0 * a[(0, 0)] * a[(3, 0)]
        + a[(3, 0)].powf(2.0)
        + a[(1, 0)].powf(2.0)
        - 2.0 * a[(1, 0)] * a[(4, 0)]
        + a[(4, 0)].powf(2.0)
        + a[(2, 0)].powf(2.0)
        - 2.0 * a[(2, 0)] * a[(5, 0)]
        + a[(5, 0)].powf(2.0);
    groebner_matrix[(1, 0)] =
        -2.0 * n[(0, 0)] * n[(6, 0)] - 2.0 * n[(1, 0)] * n[(7, 0)] - 2.0 * n[(2, 0)] * n[(8, 0)]
            + n[(0, 0)].powf(2.0)
            + n[(1, 0)].powf(2.0)
            + n[(2, 0)].powf(2.0)
            + n[(6, 0)].powf(2.0)
            + n[(7, 0)].powf(2.0)
            + n[(8, 0)].powf(2.0);
    groebner_matrix[(1, 1)] =
        2.0 * a[(0, 0)] * n[(0, 0)] + 2.0 * a[(1, 0)] * n[(1, 0)] + 2.0 * a[(2, 0)] * n[(2, 0)]
            - 2.0 * a[(0, 0)] * n[(6, 0)]
            - 2.0 * n[(0, 0)] * a[(6, 0)]
            + 2.0 * a[(6, 0)] * n[(6, 0)]
            - 2.0 * a[(1, 0)] * n[(7, 0)]
            - 2.0 * n[(1, 0)] * a[(7, 0)]
            + 2.0 * a[(7, 0)] * n[(7, 0)]
            - 2.0 * a[(2, 0)] * n[(8, 0)]
            - 2.0 * n[(2, 0)] * a[(8, 0)]
            + 2.0 * a[(8, 0)] * n[(8, 0)];
    groebner_matrix[(1, 2)] =
        -c02w + a[(0, 0)].powf(2.0) + a[(1, 0)].powf(2.0) + a[(2, 0)].powf(2.0)
            - 2.0 * a[(0, 0)] * a[(6, 0)]
            + a[(6, 0)].powf(2.0)
            - 2.0 * a[(1, 0)] * a[(7, 0)]
            + a[(7, 0)].powf(2.0)
            - 2.0 * a[(2, 0)] * a[(8, 0)]
            + a[(8, 0)].powf(2.0);
    groebner_matrix[(2, 0)] =
        -2.0 * n[(0, 0)] * n[(9, 0)] - 2.0 * n[(1, 0)] * n[(10, 0)] - 2.0 * n[(2, 0)] * n[(11, 0)]
            + n[(0, 0)].powf(2.0)
            + n[(1, 0)].powf(2.0)
            + n[(2, 0)].powf(2.0)
            + n[(9, 0)].powf(2.0)
            + n[(10, 0)].powf(2.0)
            + n[(11, 0)].powf(2.0);
    groebner_matrix[(2, 1)] =
        2.0 * a[(0, 0)] * n[(0, 0)] + 2.0 * a[(1, 0)] * n[(1, 0)] + 2.0 * a[(2, 0)] * n[(2, 0)]
            - 2.0 * a[(0, 0)] * n[(9, 0)]
            - 2.0 * n[(0, 0)] * a[(9, 0)]
            + 2.0 * a[(9, 0)] * n[(9, 0)]
            - 2.0 * a[(1, 0)] * n[(10, 0)]
            - 2.0 * n[(1, 0)] * a[(10, 0)]
            + 2.0 * a[(10, 0)] * n[(10, 0)]
            - 2.0 * a[(2, 0)] * n[(11, 0)]
            - 2.0 * n[(2, 0)] * a[(11, 0)]
            + 2.0 * a[(11, 0)] * n[(11, 0)];
    groebner_matrix[(2, 2)] =
        -c03w + a[(0, 0)].powf(2.0) + a[(1, 0)].powf(2.0) + a[(2, 0)].powf(2.0)
            - 2.0 * a[(0, 0)] * a[(9, 0)]
            + a[(9, 0)].powf(2.0)
            - 2.0 * a[(1, 0)] * a[(10, 0)]
            + a[(10, 0)].powf(2.0)
            - 2.0 * a[(2, 0)] * a[(11, 0)]
            + a[(11, 0)].powf(2.0);
}
